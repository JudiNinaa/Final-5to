drop table if exists calendario, avisos_leidos, aviso_dest, avisos, asistencia_prof, docencia,
  asistencias, notas, libro, asignaciones, alumnos, materias, divisiones, usuarios cascade;

create table usuarios(
  id bigint generated by default as identity primary key,
  usuario varchar(40) not null unique,
  clave text not null,
  nombre varchar(100) not null,
  rol varchar(10) not null check (rol in ('creador','directivo','preceptor','profesor','alumno')),
  telefono varchar(30),
  clave_extra text);
create table divisiones(
  id bigint generated by default as identity primary key,
  anio smallint not null check (anio between 1 and 6),
  nombre varchar(10) not null,
  horario_url text);
create table materias(
  id bigint generated by default as identity primary key,
  anio smallint not null,
  nombre varchar(80) not null);
create table alumnos(
  id bigint generated by default as identity primary key,
  nombre varchar(100) not null,
  division_id bigint not null references divisiones(id) on delete cascade,
  usuario_id bigint references usuarios(id) on delete set null);
create table asignaciones(
  usuario_id bigint references usuarios(id) on delete cascade,
  division_id bigint references divisiones(id) on delete cascade,
  primary key(usuario_id, division_id));
create table docencia(
  usuario_id bigint references usuarios(id) on delete cascade,
  materia_id bigint references materias(id) on delete cascade,
  primary key(usuario_id, materia_id));
create table asistencias(
  alumno_id bigint references alumnos(id) on delete cascade,
  fecha date not null,
  materia_id bigint not null default 0,
  estado char(1) not null check (estado in ('P','A','T','R')),
  primary key(alumno_id, fecha, materia_id));
create table asistencia_prof(
  usuario_id bigint references usuarios(id) on delete cascade,
  fecha date not null,
  estado char(1) not null check (estado in ('P','A','T')),
  primary key(usuario_id, fecha));
create table libro(
  id bigint generated by default as identity primary key,
  division_id bigint not null references divisiones(id) on delete cascade,
  materia_id bigint not null references materias(id) on delete cascade,
  tipo varchar(10) not null check (tipo in ('tema','examen')),
  fecha date not null,
  texto text not null,
  autor_id bigint references usuarios(id) on delete set null);
create table notas(
  id bigint generated by default as identity primary key,
  alumno_id bigint not null references alumnos(id) on delete cascade,
  materia_id bigint not null references materias(id) on delete cascade,
  titulo varchar(120) not null,
  nota numeric(3,1) not null check (nota between 1 and 10),
  fecha date not null default current_date,
  prof_id bigint references usuarios(id) on delete set null);
create table avisos(
  id bigint generated by default as identity primary key,
  autor_id bigint references usuarios(id) on delete cascade,
  tipo varchar(10) not null,
  titulo varchar(120) not null,
  texto text not null,
  fecha_ref date,
  creado timestamptz not null default now());
create table aviso_dest(
  aviso_id bigint references avisos(id) on delete cascade,
  division_id bigint references divisiones(id) on delete cascade,
  primary key(aviso_id, division_id));
create table avisos_leidos(
  aviso_id bigint references avisos(id) on delete cascade,
  usuario_id bigint references usuarios(id) on delete cascade,
  primary key(aviso_id, usuario_id));
create table calendario(
  id bigint generated by default as identity primary key,
  anio smallint not null,
  fecha date not null,
  tipo varchar(12) not null check (tipo in ('sin_clases','recreacion','otro')),
  descripcion varchar(200));

